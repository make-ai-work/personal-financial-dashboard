// End-to-end check of the Retirement tab (Plan + Monte Carlo + saved versions). Run:  npm run build && npm run test:e2e:retirement
import { createRequire } from 'node:module'
import { spawn } from 'node:child_process'
import { mkdirSync } from 'node:fs'
import assert from 'node:assert/strict'
import { autoSignIn } from './signin.mjs'

const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const OUT = process.env.E2E_OUT || '/tmp/retirement-e2e'
mkdirSync(OUT, { recursive: true })
const PASS = 'correct horse battery staple'

const server = spawn('npx', ['vite', 'preview', '--port', '4179', '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 2500))
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true })
await ctx.route(/open-meteo\.com/, (r) => r.fulfill({ json: { current: { temperature_2m: 20, relative_humidity_2m: 50, weather_code: 1, wind_speed_10m: 5, us_aqi: 40 }, daily: { time: ['2026-11-16', '2026-11-17'], weather_code: [1, 1], temperature_2m_max: [22, 22], temperature_2m_min: [12, 12] } } })) // Home's weather: not under test here
await ctx.addInitScript(() => { delete window.showSaveFilePicker; delete window.showOpenFilePicker; localStorage.setItem('google.setupSkipped', '1') })
const PER_USD = { USD: 1, INR: 84, GBP: 0.8, AUD: 1.5, CHF: 0.9 }
await ctx.route('**/api.frankfurter.dev/**', (r) => {
  const u = new URL(r.request().url())
  const base = u.searchParams.get('base')
  const symbols = u.searchParams.get('symbols').split(',')
  r.fulfill({ json: { base, date: '2026-10-31', rates: Object.fromEntries(symbols.map((s) => [s, PER_USD[s] / PER_USD[base]])) } })
})
const page = await ctx.newPage()
autoSignIn(page)
await page.clock.setFixedTime(new Date('2026-10-31T12:00:00'))
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const step = (s) => console.log('•', s)
const split = async (page, l, r) => { // the two columns are 70 : 30 of the width they share
  const a = await page.locator(l).first().boundingBox(), b = await page.locator(r).first().boundingBox()
  assert.ok(Math.abs(a.width / (a.width + b.width + 16) - 0.7) < 0.02 && b.x > a.x + a.width - 2, `70 : 30, got ${JSON.stringify([a.width, b.width])}`)
}

const dialog = () => page.getByRole('dialog')
const subtab = (name) => page.locator('.subtabs').getByRole('button', { name })
const topTab = (name) => page.getByRole('tab', { name })

async function addFinanceAsset(name, institution, balance, owner) {
  await page.getByRole('button', { name: '+ Add asset' }).click()
  await dialog().getByLabel('Account name').fill(name)
  await dialog().getByLabel('Bank / holding company').fill(institution)
  await dialog().getByLabel(/Current balance/).fill(balance)
  await dialog().locator('.radios label', { hasText: new RegExp('^' + owner) }).click()
  await dialog().getByRole('button', { name: 'Save' }).click()
  await dialog().waitFor({ state: 'detached' })
}
const kpi = (label) => page.locator('.kpi', { hasText: label }).locator('b').first()
const settle = async () => { await page.waitForTimeout(400); await page.getByText('calculating…').waitFor({ state: 'detached' }) }
const chance = async () => { await settle(); return parseFloat((await kpi('Chance your savings last').innerText()).replace('%', '')) }
const setSpend = async (v) => { await subtab('Plan').click(); await page.getByLabel('Spending in retirement').fill(String(v)); await subtab('Monte Carlo').click(); return chance() }
const overflow = () => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)

try {
  await page.goto('http://localhost:4179/')
  await topTab('Finance Dashboard').click()
  step('create the vault and three Finance assets (two USD, one INR)')
  await page.getByRole('button', { name: /Create a new vault file/ }).click()
  await page.getByLabel('Passphrase', { exact: true }).fill(PASS)
  await page.getByLabel('Confirm passphrase').fill(PASS)
  await page.getByRole('checkbox').check()
  await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Create encrypted file' }).click()])
  await page.getByText('Update date', { exact: true }).waitFor()
  await subtab(/USA/).click()
  await addFinanceAsset('Brokerage', 'Schwab', '96000', 'Joint')
  await addFinanceAsset('401(k)', 'Fidelity', '184000', 'Mine')
  await subtab(/India/).click()
  await addFinanceAsset('Mutual funds', 'Zerodha', '4200000', 'Mine')

  step('Plan page: nothing ticked yet, then tick accounts: INR is converted at 1 USD = 84 INR')
  await topTab(/Retirement/).click()
  await page.getByText('Savings used for the plan').waitFor()
  const savings = page.locator('.rowf', { hasText: 'Invested savings today' })
  assert.match(await savings.innerText(), /\$ 0/)
  await page.getByLabel('Use Brokerage').check()
  await page.getByLabel('Use 401(k)').check()
  assert.match(await savings.innerText(), /\$ 280,000/)
  await page.getByLabel('Use Mutual funds').check()
  assert.match(await savings.innerText(), /\$ 330,000/) // 280,000 + 4,200,000 / 84
  await page.getByLabel('Adjustment').fill('-30000')
  assert.match(await savings.innerText(), /\$ 300,000/)
  await page.getByLabel('Adjustment').fill('0')

  step('Plan page: results appear, the yield sensitivity table is there, and a bad age is reported')
  await page.getByText('Nest egg needed at retirement').waitFor()
  await split(page, '.sp-l', '.sp-r') // results left, the inputs right
  assert.equal(await page.locator('table tbody tr').count(), 5)
  await page.getByLabel('Retirement age').fill('30')
  await page.getByText('Retirement age cannot be before your current age.').waitFor()
  await page.getByLabel('Retirement age').fill('65')
  await page.getByText('Retirement age cannot be before your current age.').waitFor({ state: 'detached' })

  step('income source in INR is converted; market figures start as placeholders and go stale after a month')
  await page.getByText('Income in retirement').waitFor()
  await page.getByRole('button', { name: '+ Add source' }).click()
  await page.getByLabel('New source amount').fill('840000')
  await page.getByLabel('New source currency').selectOption('INR')
  await page.getByLabel('New source from age').fill('60')
  await page.getByText(/These are placeholder values/).waitFor()
  await page.getByLabel('Market figures date').fill('2026-09-01')
  await page.getByText(/Market figures are 60 days old/).waitFor()
  await page.getByLabel('Market figures date').fill('2026-10-20')
  await page.getByText(/Market figures are/).waitFor({ state: 'detached' })
  await page.getByLabel('Equity share of portfolio').fill('70')
  await page.getByText('typed by you').waitFor()

  step('Monte Carlo: results, the three charts, and exact repeatability for the same seed')
  await subtab('Monte Carlo').click()
  await split(page, '.mainc', '.side') // results left, saved versions and the comparison right
  await page.getByLabel('Equities weight').fill('70'); await page.getByLabel('Bonds weight').fill('25'); await page.getByLabel('Cash equivalents weight').fill('5'); await page.getByLabel('Precious metals weight').fill('0')
  const p1 = await chance()
  assert.ok(p1 > 5 && p1 < 100, `chance ${p1}`)
  await page.getByRole('img', { name: 'Range of possible net worth by age' }).waitFor()
  await page.getByRole('img', { name: 'Chance your savings last, by age' }).waitFor()
  await page.getByText('Projected Net Worth').waitFor()
  assert.match(await page.getByTestId('retsum').innerText(), /Mix: 100\.0%.*swing about \d+\.\d%/)
  await page.getByLabel('Random seed').fill('777'); const pOther = await chance()
  await page.getByLabel('Random seed').fill('12345'); assert.equal(await chance(), p1)
  void pOther

  step('more spending lowers the chance; the flexible rule raises it')
  const base = await chance()
  const high = await setSpend(160000)
  assert.ok(high < base, `${high} should be below ${base}`)
  const low = await setSpend(40000)
  assert.ok(low > base, `${low} should be above ${base}`)
  await setSpend(90000)
  const fixed = await chance()
  await page.getByLabel('Spending rule').selectOption('flex')
  const flex = await chance()
  assert.ok(flex >= fixed, `flexible ${flex} < fixed ${fixed}`)
  await page.getByLabel('Spending rule').selectOption('fixed')

  step('impossible correlations are explained and "Make valid" repairs them')
  await page.getByLabel('Correlation eqbd').fill('0.9'); await page.getByLabel('Correlation eqcash').fill('-0.9'); await page.getByLabel('Correlation bdcash').fill('0.9')
  await page.getByTestId('corerr').waitFor()
  await page.getByText(/not mathematically possible together, so nothing can be simulated/).waitFor()
  await page.getByRole('button', { name: 'Make valid' }).click()
  await page.getByTestId('corerr').waitFor({ state: 'detached' })
  await chance()
  await page.getByRole('button', { name: 'Reset to defaults' }).click()
  await page.getByLabel('Spending rule').selectOption('fixed')

  step('versions: save three, the fourth is blocked, load restores the inputs')
  const saveBtn = page.getByRole('button', { name: 'Save as new version' })
  const versions = page.getByTestId('version')
  await setSpend(80000)
  await page.getByLabel('New version name').fill('Base case'); await saveBtn.click()
  await page.getByText('1 of 3 used').waitFor()
  const baseChance = await chance()
  await setSpend(60000)
  await page.getByLabel('New version name').fill('Spend less'); await saveBtn.click()
  await setSpend(100000)
  await page.getByLabel('New version name').fill('Spend more'); await saveBtn.click()
  await page.getByText('3 of 3 used').waitFor()
  assert.equal(await versions.count(), 3)
  assert.ok(await saveBtn.isDisabled())
  await page.getByText(/All 3 slots are used/).waitFor()
  await page.getByText('Compare versions').waitFor()
  assert.equal(await page.locator('#cmp tbody tr').count(), 4) // three versions + current
  const cmp = await page.locator('#cmp').innerText()
  assert.match(cmp, /1\. Base case/); assert.match(cmp, /Current \(unsaved\)/)
  await versions.filter({ hasText: 'Base case' }).getByRole('button', { name: 'Load' }).click()
  await subtab('Plan').click()
  assert.equal(await page.getByLabel('Spending in retirement').inputValue(), '80000')
  await subtab('Monte Carlo').click()
  assert.equal(await chance(), baseChance, 'loading a version reproduces its chance exactly')

  step('overwrite, rename and delete (with confirmation) free a slot')
  await subtab('Plan').click(); await page.getByLabel('Spending in retirement').fill('85000'); await subtab('Monte Carlo').click(); await settle()
  await versions.filter({ hasText: 'Base case' }).getByRole('button', { name: 'Overwrite with current' }).click()
  await page.getByText(/Retire at 65 · spend \$ 85,000/).first().waitFor()
  await versions.filter({ hasText: 'Spend less' }).getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('Version name', { exact: true }).fill('Frugal'); await page.getByLabel('Version name', { exact: true }).press('Enter')
  await versions.filter({ hasText: 'Frugal' }).waitFor()
  page.once('dialog', (d) => d.dismiss())
  await versions.filter({ hasText: 'Frugal' }).getByRole('button', { name: 'Delete' }).click()
  assert.equal(await versions.count(), 3)
  page.once('dialog', (d) => d.accept())
  await versions.filter({ hasText: 'Frugal' }).getByRole('button', { name: 'Delete' }).click()
  await page.getByText('2 of 3 used').waitFor()
  assert.ok(await saveBtn.isEnabled())

  step('lock, unlock: plan, assumptions and versions come back from the encrypted file')
  await page.getByLabel('Random seed').fill('4242'); await settle()
  await page.getByRole('button', { name: 'Lock now' }).click()
  await page.getByPlaceholder('Passphrase').fill(PASS)
  await page.getByRole('button', { name: 'Unlock' }).click()
  await subtab('Monte Carlo').click()
  await page.getByText(/2 of 3 used/).waitFor()
  assert.equal(await page.getByLabel('Random seed').inputValue(), '4242')
  await subtab('Plan').click()
  assert.ok(await page.getByLabel('Use Brokerage').isChecked())
  assert.equal(await page.getByLabel('Equity share of portfolio').inputValue(), '70')
  await subtab('Monte Carlo').click(); await chance()
  await page.screenshot({ path: `${OUT}/desktop.png`, fullPage: true })
  assert.equal(await overflow(), 0, 'no sideways scroll on desktop')

  step('phone: simpler layout, no sideways scrolling, advanced assumptions folded away')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(300); await chance()
  assert.equal(await overflow(), 0, 'no sideways scroll on phone (Monte Carlo)')
  assert.equal(await page.getByText('When it runs out').count(), 0, 'histogram is a desktop-only extra')
  assert.equal(await page.locator('.kpi', { hasText: 'Chance your savings last' }).count(), 1)
  assert.equal(await page.locator('.kpi', { hasText: '10th to 90th percentile' }).count(), 0)
  assert.equal(await page.getByLabel('Equities weight').isVisible(), false, 'assumptions folded away')
  await page.getByText('Advanced: assumptions').click()
  assert.ok(await page.getByLabel('Equities weight').isVisible())
  await page.screenshot({ path: `${OUT}/phone-mc.png`, fullPage: true })
  await subtab('Plan').click()
  assert.equal(await overflow(), 0, 'no sideways scroll on phone (Plan)')
  assert.equal(await page.getByText('Sensitivity to the 10-year yield').count(), 0)
  assert.equal(await page.getByLabel('Contribution growth / yr (%)').count(), 0)
  await page.getByText('Savings used for the plan').click().catch(() => {})
  await page.screenshot({ path: `${OUT}/phone-plan.png`, fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.waitForTimeout(300)
  assert.equal(await page.getByLabel('Contribution growth / yr (%)').count(), 1, 'desktop layout is back')
} catch (e) {
  await page.screenshot({ path: `${OUT}/failure.png`, fullPage: true })
  console.error('FAILED:', e.message)
  await browser.close(); server.kill(); process.exit(1)
}
console.log('page errors:', errors.length ? errors.join(' | ') : 'none')
assert.equal(errors.length, 0)
await browser.close(); server.kill()
console.log('RETIREMENT E2E PASSED')
