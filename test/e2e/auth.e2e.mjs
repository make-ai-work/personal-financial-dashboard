  await ans.fill('9999'); await chk.click(); await ans.fill('9999'); await chk.click()
  await page.getByText(/Wait \d+ seconds, then try again/).waitFor(); assert.ok(await ans.isDisabled()); assert.ok(await gbtn.isDisabled())
