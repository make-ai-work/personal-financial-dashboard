// End-to-end check of the placeholder sign-in. Run:  npm run build && npm run test:e2e:auth
import { createRequire } from 'node:module'
import { spawn } from 'node:child_process'
import assert from 'node:assert/strict'

const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const server = spawn('npx', ['vite', 'preview', '--port', '4180', '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 2500))
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } })
await ctx.addInitScript(() => { delete window.showSaveFilePicker; delete window.showOpenFilePicker })
// Google is stubbed: a fake sign-in script (window.__gsiMode = 'ok' | 'closed') and the userinfo answer
await ctx.route(/accounts\.google\.com\/gsi\/client/, (r) => r.fulfill({ contentType: 'text/javascript', body: `window.__gsiMode='ok';window.__gsiCalls=0;window.google={accounts:{oauth2:{initTokenClient:function(c){return{requestAccessToken:function(o){window.__gsiCalls++;window.__gsiArgs={client:c.client_id,scope:c.scope,prompt:o&&o.prompt};if(window.__gsiMode==='closed')c.error_callback({type:'popup_closed'});else setTimeout(function(){c.callback({access_token:'T'})},50)}}},revoke:function(t,cb){window.__revoked=t;cb&&cb()}}}}` }))
await ctx.route(/googleapis\.com\/oauth2\/v3\/userinfo/, (r) => r.fulfill({ json: { sub: '1001', email: 'sam@example.com', name: 'Sam Example', email_verified: true } }))
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
const step = (s) => console.log('•', s)
const wantSignIn = () => page.getByRole('button', { name: /Sign in with Google/ }).waitFor()

try {
  await page.goto('http://localhost:4180/')
  step('first visit asks for the Google client ID before anything else, and no tab is shown')
  await page.getByRole('heading', { name: 'Connect your Google account' }).waitFor()
  assert.equal(await page.getByRole('tab').count(), 0)
  const box = page.getByLabel('OAuth client ID'), save = page.getByRole('button', { name: 'Save and continue' })
  assert.ok(await save.isDisabled())
  await box.fill('hello'); await page.getByText(/does not look like a client ID/).waitFor(); assert.ok(await save.isDisabled())
  await box.fill('GOCSPX-abc123'); await page.getByText(/looks like a client secret/).waitFor(); assert.ok(await save.isDisabled())
  await box.fill(''); await page.getByText('Looks right.').waitFor({ state: 'detached' })
  await page.getByText('How do I get one?').waitFor()
  await page.getByText('http://localhost:4180').first().waitFor() // the address to authorise
  step('a valid ID is saved in the browser, the confirmation card stays until Continue, then sign-in')
  const ID = '123456789012-abcdefghij1234.apps.googleusercontent.com'
  await box.fill(ID); await page.getByText('Looks right.').waitFor(); await save.click()
  await page.getByRole('heading', { name: 'Google is set up' }).waitFor()
  await page.getByText(ID).waitFor(); await page.getByText(/ready to sign in/).waitFor()
  await page.reload()
  await wantSignIn() // remembered across reloads, no setup again
  step('first visit, skipping setup goes to the demo sign-in and is remembered')
  await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.getByRole('heading', { name: 'Connect your Google account' }).waitFor()
  await page.getByRole('button', { name: /Skip for now/ }).click()
  await wantSignIn()
  await page.reload(); await wantSignIn()
  step('first visit, sign-in screen is labelled as a demo')
  assert.equal(await page.getByRole('tab').count(), 0, 'no tabs before signing in')
  await page.getByText(/Demo sign-in/).waitFor()

  step('the Google button signs in and the app opens; it survives a reload')
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.getByRole('tab', { name: 'Home' }).waitFor()
  await page.reload()
  await page.getByRole('tab', { name: 'Home' }).waitFor()

  step('account dialog shows the demo user and says the two-step check is on hold')
  await page.getByRole('button', { name: 'Account' }).click()
  await page.getByText(/not a real Google account/).waitFor()
  await page.getByText(/on hold: nothing is enforced/).waitFor()

  step('the Account dialog can set up or change the client ID later')
  await page.getByText('Not set up (demo sign-in)').waitFor()
  await page.getByRole('button', { name: 'Set up' }).click()
  await page.getByLabel('OAuth client ID').fill('GOCSPX-nope'); assert.ok(await page.getByRole('button', { name: 'Save', exact: true }).isDisabled())
  await page.getByLabel('OAuth client ID').fill(ID); await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByText(/Client ID 123456789012-abcdefghij1/).waitFor()
  await page.getByRole('button', { name: 'Change' }).click()
  assert.equal(await page.getByLabel('OAuth client ID').inputValue(), ID)
  await page.keyboard.press('Escape') // closes only the top dialog
  await page.getByRole('heading', { name: 'Google connection' }).waitFor({ state: 'detached' })
  await page.getByText(/Client ID 123456789012-abcdefghij1/).waitFor() // the Account dialog is still open
  step('sign out returns to sign-in; with the two-step preview on, the code screen sits in between')
  await page.getByLabel(/Preview the two-step verification/).check()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await wantSignIn()
  await page.getByText(/Only your name and email are read/).waitFor() // a client ID is saved: the real sign-in
  step('real Google sign-in: closing the window is explained; nothing opens the app')
  await page.getByRole('button', { name: /Sign in with Google/ }).click() // loads the (fake) Google script first
  await page.getByRole('heading', { name: 'Two-step verification' }).waitFor()
  await page.getByRole('button', { name: 'Cancel' }).click(); await wantSignIn()
  await page.evaluate(() => { window.__gsiMode = 'closed' })
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.getByRole('alert').getByText(/window was closed before it finished/).waitFor()
  assert.equal(await page.getByRole('tab').count(), 0)
  await page.evaluate(() => { window.__gsiMode = 'ok' })
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.getByRole('heading', { name: 'Two-step verification' }).waitFor()
  assert.equal(await page.getByRole('tab').count(), 0, 'app stays closed until the step is passed')
  assert.ok(await page.getByRole('button', { name: 'Verify' }).isDisabled())
  await page.getByLabel('Verification code').fill('12ab34')
  assert.equal(await page.getByLabel('Verification code').inputValue(), '1234') // letters are dropped
  await page.getByLabel('Verification code').fill('123456')
  await page.getByRole('button', { name: 'Verify' }).click()
  await page.getByRole('tab', { name: 'Home' }).waitFor()

  step('the Account dialog shows the real Google identity; only identity was asked for and nothing is kept')
  await page.getByRole('button', { name: 'Account' }).click()
  await page.getByText(/Sam Example/).first().waitFor(); await page.getByText(/sam@example\.com/).waitFor(); await page.getByText('Signed in with your Google account.').waitFor()
  const g = await page.evaluate(() => ({ args: window.__gsiArgs, revoked: window.__revoked, stored: localStorage.getItem('auth.user'), keys: Object.keys(localStorage) }))
  assert.deepEqual([g.args.client, g.args.scope, g.args.prompt], [ID, 'openid email profile', 'select_account'])
  assert.equal(g.revoked, 'T', 'the access pass is revoked straight away')
  assert.deepEqual(Object.keys(JSON.parse(g.stored)).sort(), ['email', 'id', 'name', 'picture', 'verified'])
  assert.ok(!JSON.stringify(g).includes('access_token'))
  step('cancel from the code screen goes back to sign-in; turning the preview off skips the step')
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.getByRole('button', { name: 'Cancel' }).click()
  await wantSignIn()
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.getByLabel('Verification code').fill('000000'); await page.getByRole('button', { name: 'Verify' }).click()
  await page.getByRole('button', { name: 'Account' }).click()
  await page.getByLabel(/Preview the two-step verification/).uncheck()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.getByRole('tab', { name: 'Home' }).waitFor()

  step('phone: setup, sign-in and account are usable without scrolling sideways; help starts folded')
  await page.getByRole('button', { name: 'Account' }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('heading', { name: 'Connect your Google account' }).waitFor()
  assert.equal(await page.locator('details.howto').evaluate((d) => d.open), false)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth), 0)
  await page.getByRole('button', { name: /Skip for now/ }).click()
  await page.getByRole('button', { name: /Sign in with Google/ }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth), 0)
  await page.getByRole('button', { name: 'Account' }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await wantSignIn()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth), 0)
} catch (e) {
  await page.screenshot({ path: '/tmp/auth-failure.png', fullPage: true })
  console.error('FAILED:', e.message)
  await browser.close(); server.kill(); process.exit(1)
}
console.log('page errors:', errors.length ? errors.join(' | ') : 'none')
assert.equal(errors.length, 0)
await browser.close(); server.kill()
console.log('AUTH E2E PASSED')
