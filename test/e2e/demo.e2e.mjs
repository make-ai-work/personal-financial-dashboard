// End-to-end check of the demo build (sample data, no saving). Run:  npm run build:demo && npm run test:e2e:demo
import { createRequire } from 'node:module'
import { spawn } from 'node:child_process'
import { mkdirSync } from 'node:fs'
import assert from 'node:assert/strict'

const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const OUT = process.env.E2E_OUT || '/tmp/demo-e2e'
mkdirSync(OUT, { recursive: true })

const server = spawn('npx', ['vite', 'preview', '--outDir', 'dist-demo', '--port', '4182', '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => setTimeout(r, 2500))
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true })
await ctx.addInitScript(() => { delete window.showSaveFilePicker; delete window.showOpenFilePicker })
const PER_USD = { USD: 1, INR: 84, GBP: 0.8, AUD: 1.5, CHF: 0.9 }
await ctx.route('**/api.frankfurter.dev/**', (r) => {
  const u = new URL(r.request().url())
  const base = u.searchParams.get('base')
  const symbols = u.searchParams.get('symbols').split(',')
  r.fulfill({ json: { base, date: '2026-11-14', rates: Object.fromEntries(symbols.map((s) => [s, PER_USD[s] / PER_USD[base]])) } })
})
const page = await ctx.newPage()
await page.clock.setFixedTime(new Date('2026-11-15T12:00:00'))
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const step = (s) => console.log('•', s)
const dialog = () => page.getByRole('dialog')
const topTab = (name) => page.getByRole('tab', { name })
const subtab = (name) => page.locator('.subtabs').getByRole('button', { name })
const demoBtn = () => page.getByRole('button', { name: 'Demo Mode (skip sign in)' })
const overflow = () => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
const enter = async () => { await demoBtn().click(); await page.getByText('Sample data · nothing is saved').waitFor() }

try {
  await page.goto('http://localhost:4182/')
  step('the sign-in page is kept: Google button inactive, Demo Mode active, no setup screen, no tabs')
  const google = page.getByRole('button', { name: /Sign in with Google/ })
  await google.waitFor()
  assert.ok(await google.isDisabled(), 'Google sign-in is inactive in the demo')
  assert.ok(await demoBtn().isEnabled())
  await page.getByText(/This is the demo/).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Connect your Google account' }).count(), 0)
  assert.equal(await page.getByRole('tab').count(), 0)
  await google.click({ force: true, timeout: 1000 }).catch(() => {})
  assert.equal(await page.getByRole('tab').count(), 0, 'clicking the disabled button does nothing')

  step('Demo Mode opens the app with sample data, the DEMO banner and no file, lock or passphrase controls')
  await enter()
  await page.getByText('Sample data.', { exact: false }).first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'Lock now' }).count(), 0)
  await topTab('Finance Dashboard').click()
  await page.getByText('Summary ·').waitFor()
  const summary = await page.locator('.panel', { hasText: 'Summary ·' }).first().innerText()
  assert.match(summary, /USA/); assert.match(summary, /India/); assert.match(summary, /Total in USD/)
  await subtab(/USA/).click()
  await page.getByText('Sample Brokerage').first().waitFor(); await page.getByText('401(k)').first().waitFor(); await page.getByText('Car loan').waitFor()
  await subtab('Settings').click()
  await page.getByText('Export decrypted Excel copy').waitFor()
  for (const gone of ['Change passphrase', 'Lock now', 'Change file', 'Auto-lock after']) assert.equal(await page.getByText(gone).count(), 0, gone)

  step('the demo is editable: add an account, it shows up, and Download Excel copy works')
  await subtab(/USA/).click()
  await page.getByRole('button', { name: '+ Add asset' }).click()
  await dialog().getByLabel('Account name').fill('My test account')
  await dialog().getByLabel('Bank / holding company').fill('Test Bank')
  await dialog().getByLabel(/Current balance/).fill('1234')
  await dialog().locator('.radios label', { hasText: /^Mine/ }).click()
  await dialog().getByRole('button', { name: 'Save' }).click()
  await dialog().waitFor({ state: 'detached' })
  await page.getByText('My test account').waitFor()
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download Excel copy' }).click()])
  assert.match(dl.suggestedFilename(), /\.xlsx$/)

  step('Reset sample data brings the original back')
  await page.getByRole('button', { name: 'Reset sample data' }).click()
  await page.getByText('My test account').waitFor({ state: 'detached' })
  await page.getByText('Sample Brokerage').first().waitFor()

  step('the other tabs have sample data too')
  await topTab(/Property/).click()
  await page.getByText('Maple Street home').first().waitFor()
  await topTab(/Portfolio/).click()
  await page.getByText('Portfolio summary').waitFor()
  await subtab(/USA/).click()
  await page.getByText(/Unallocated/).first().waitFor()
  await topTab(/Retirement/).click()
  await page.getByText('Savings used for the plan').waitFor()
  assert.ok(await page.getByLabel('Use Sample Brokerage').isChecked())
  await page.getByText('Nest egg needed at retirement').waitFor()

  step('Retirement: two saved versions are there and a third can be saved (editable); Load works')
  await subtab('Monte Carlo').click()
  await page.getByText('2 of 3 used').waitFor()
  await page.getByRole('heading', { name: '1. Base case' }).waitFor(); await page.getByRole('heading', { name: '2. Retire at 65' }).waitFor()
  await page.waitForTimeout(500)
  const chanceText = await page.locator('.kpi', { hasText: 'Chance your savings last' }).locator('b').first().innerText()
  assert.match(chanceText, /^\d+(\.\d)?%$/)
  await page.getByLabel('New version name').fill('My version')
  await page.getByRole('button', { name: 'Save as new version' }).click()
  await page.getByText('3 of 3 used').waitFor()
  await page.getByTestId('version').filter({ hasText: 'Retire at 65' }).getByRole('button', { name: 'Load' }).click()
  await subtab('Plan').click()
  assert.equal(await page.getByLabel('Retirement age').inputValue(), '65')

  step('the Account dialog: Google controls inactive; Sign out returns to the sign-in page and the data resets')
  await page.getByRole('button', { name: 'Account' }).click()
  await page.getByText('Not available in the demo').first().waitFor()
  assert.ok(await page.getByRole('button', { name: 'Set up' }).isDisabled())
  assert.ok(await page.getByLabel(/Preview the two-step verification/).isDisabled())
  await page.getByRole('button', { name: 'Sign out' }).click()
  await demoBtn().waitFor()
  await enter()
  await topTab(/Retirement/).click(); await subtab('Monte Carlo').click()
  await page.getByText('2 of 3 used').waitFor() // the third version is gone

  step('a reload also returns to the sign-in page with fresh data')
  await page.reload()
  await demoBtn().waitFor()
  assert.equal(await page.getByRole('tab').count(), 0)

  step('phone: banner and tabs fit, no sideways scrolling')
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await overflow(), 0, 'sign-in page')
  await enter()
  await page.getByText('Sample data.', { exact: false }).first().waitFor()
  await topTab('Finance Dashboard').click(); await page.getByText('Summary ·').waitFor()
  assert.equal(await overflow(), 0, 'Finance')
  await topTab(/Retirement/).click(); await page.waitForTimeout(600)
  assert.equal(await overflow(), 0, 'Retirement')
  await page.screenshot({ path: `${OUT}/phone.png`, fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await topTab('Finance Dashboard').click(); await page.getByText('Summary ·').waitFor()
  await page.screenshot({ path: `${OUT}/desktop.png`, fullPage: true })
} catch (e) {
  await page.screenshot({ path: `${OUT}/failure.png`, fullPage: true })
  console.error('FAILED:', e.message)
  await browser.close(); server.kill(); process.exit(1)
}
console.log('page errors:', errors.length ? errors.join(' | ') : 'none')
assert.equal(errors.length, 0)
await browser.close(); server.kill()
console.log('DEMO E2E PASSED')
